//! Unicode tables pinned to the oracle's Python (3.11, Unicode 14.0), so the
//! core's string rules do not drift with Rust's newer Unicode.
//!
//! - [`ND_ZEROS`]: the zero of every run of Unicode `Nd` digits. Python's
//!   `re` `\d` and `int()` accept any `Nd` digit, so `UnityVersion.from_str`
//!   does (`helpers/UnityVersion.py:62-88`, plan section 3.4).
//! - [`LOWER_EXCEPTIONS`]: code points whose `str.lower()` under Unicode 14.0
//!   differs from Rust's `char::to_lowercase`, with Python's result. Every
//!   other code point lowers as Rust lowers it ([`crate::pystr::py_lower`],
//!   plan risk R7).
//!
//! Owner: package A. Both tables are generated by `tools/gen/gen_tables.py`
//! in the oracle image, with a header naming the generator and its Python.
//! The scaffold seeds [`ND_ZEROS`] with ASCII `0` so the version parser works
//! before the generator lands; the lookups are implemented.

/// The first code point of each `Nd` run (each run is ten digits, 0-9),
/// sorted.
pub static ND_ZEROS: &[u32] = &[0x30];

/// `(code point, Python's lower-case string)` pairs, sorted by code point.
pub static LOWER_EXCEPTIONS: &[(u32, &str)] = &[];

/// The digit value of `c` if it is a Unicode `Nd` digit (as Python 3.11 sees it).
#[must_use]
pub fn nd_digit(c: char) -> Option<u8> {
    let cp = u32::from(c);
    let i = ND_ZEROS.partition_point(|&z| z <= cp);
    let zero = *ND_ZEROS.get(i.checked_sub(1)?)?;
    u8::try_from(cp - zero).ok().filter(|d| *d < 10)
}

/// Python's lower-case form of `c` when it differs from Rust's.
#[must_use]
pub fn lower_exception(c: char) -> Option<&'static str> {
    let cp = u32::from(c);
    let i = LOWER_EXCEPTIONS
        .binary_search_by_key(&cp, |(k, _)| *k)
        .ok()?;
    LOWER_EXCEPTIONS.get(i).map(|(_, s)| *s)
}

#[cfg(test)]
mod tests {
    use super::{lower_exception, nd_digit};

    #[test]
    fn ascii_digits_are_seeded() {
        assert_eq!(nd_digit('0'), Some(0));
        assert_eq!(nd_digit('9'), Some(9));
        assert_eq!(nd_digit('/'), None);
        assert_eq!(nd_digit(':'), None);
        assert_eq!(nd_digit('a'), None);
        assert_eq!(lower_exception('A'), None);
    }
}
