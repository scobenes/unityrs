/// The string at a common-string offset (the low 31 bits), if the table has one.
#[must_use]
pub fn common_string(offset: u32) -> Option<&'static [u8]> {
    let i = COMMON_STRINGS
        .binary_search_by_key(&offset, |(o, _)| *o)
        .ok()?;
    COMMON_STRINGS.get(i).map(|(_, s)| *s)
}

#[cfg(test)]
mod tests {
    use super::{COMMON_STRINGS, common_string};

    #[test]
    fn the_table_is_unitypys_112_strings_at_their_running_offsets() {
        assert_eq!(COMMON_STRINGS.len(), 112);
        // UnityPy numbers each string by the bytes before it, NULs included
        // (`helpers/TypeTreeNode.py:322-326`).
        let mut offset = 0;
        for &(o, s) in COMMON_STRINGS {
            assert_eq!(o, offset, "{}", String::from_utf8_lossy(s));
            assert_eq!(common_string(o), Some(s));
            offset += u32::try_from(s.len()).unwrap() + 1;
        }
    }

    #[test]
    fn the_four_tpk_strings_are_present_and_rabexs_113th_is_not() {
        assert_eq!(common_string(0), Some(&b"AABB"[..]));
        assert_eq!(common_string(1161), Some(&b"Hash128"[..]));
        assert_eq!(common_string(1169), Some(&b"RenderingLayerMask"[..]));
        assert_eq!(common_string(1188), Some(&b"fixed_array"[..]));
        assert_eq!(common_string(1200), Some(&b"EntityId"[..]));
        // `LoadableReference` (rabex 0.2.1's 113th): UnityPy reads `"1209"`.
        assert_eq!(common_string(1209), None);
        assert_eq!(common_string(1), None);
    }
}
