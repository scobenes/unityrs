//! The common-string table that blob typetrees index with the high bit set.
//!
//! UnityPy 1.25.2's blob parser uses `get_common_strings()`
//! (`helpers/TypeTreeNode.py:120`, `:308-328`), which reads the table from its
//! bundled TPK: 112 entries. That is the 108 of its MIT `enums/CommonString.py`
//! plus 1161 `Hash128`, 1169 `RenderingLayerMask`, 1188 `fixed_array` and 1200
//! `EntityId`. The corpus uses two of the four, so a table of the 108 alone
//! fails L1. rabex's 113th string, `LoadableReference` (1209), is not in
//! UnityPy 1.25.2 and must stay out: UnityPy reads offset 1209 as `"1209"`.
//!
//! Owner: package A. `COMMON_STRINGS` is generated by `tools/gen/gen_tables.py`
//! from the oracle's UnityPy 1.25.2, with the provenance of each entry in the
//! generated header (plan section 2.6). The scaffold ships it empty; the
//! lookup is implemented.

/// `(offset, string)` pairs sorted by offset.
pub static COMMON_STRINGS: &[(u32, &[u8])] = &[];

/// The string at a common-string offset (the low 31 bits), if the table has one.
#[must_use]
pub fn common_string(offset: u32) -> Option<&'static [u8]> {
    let i = COMMON_STRINGS
        .binary_search_by_key(&offset, |(o, _)| *o)
        .ok()?;
    COMMON_STRINGS.get(i).map(|(_, s)| *s)
}
