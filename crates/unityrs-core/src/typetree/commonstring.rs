/// The string at a common-string offset (the low 31 bits), if
/// [`COMMON_STRINGS`] has one.
#[must_use]
pub fn common_string(offset: u32) -> Option<&'static [u8]> {
    let i = COMMON_STRINGS
        .binary_search_by_key(&offset, |(o, _)| *o)
        .ok()?;
    COMMON_STRINGS.get(i).map(|(_, s)| *s)
}

/// A common-string table built at run time from a TPK's strings, as
/// UnityPy's `get_common_strings()` numbers them (`helpers/TypeTreeNode.py:308-328`).
///
/// The table is as long as the strings it is built from, which a TPK
/// chooses, so it is built on a meter, each growth charged first, and holds
/// its charge for as long as it lives (plan section 3.15). It is not
/// `Clone`: a copy would be an allocation nothing charged.
#[derive(Default)]
pub struct CommonStrings {
    /// `(offset, string)`, offsets ascending.
    entries: Box<[(u32, RawStr)]>,
    /// The charge for `entries` (none for the empty default).
    _charge: Option<Charge>,
}

impl PartialEq for CommonStrings {
    fn eq(&self, other: &Self) -> bool {
        self.entries == other.entries
    }
}

impl Eq for CommonStrings {}

impl CommonStrings {
    /// The table of `strings`, in order: the first at offset 0, each next one
    /// past the code points of the one before it and its NUL (Python's
    /// `len(string) + 1`; a string that is not UTF-8, which no TPK holds,
    /// counts its bytes). A string whose offset passes `0x7FFF_FFFF`, which
    /// no blob offset can name, is left out, and so is every one after it.
    /// The table is charged to `meter` before each growth (a TPK's provider
    /// builds it on its own meter); a refused charge is the error, and
    /// nothing it would have allocated is.
    ///
    /// Each string is shared from here on: a parse that returns it clones it
    /// without allocating.
    pub fn new(
        strings: impl IntoIterator<Item = RawStr>,
        meter: &Arc<Meter>,
    ) -> Result<Self, ChargeError> {
        let mut entries = MeteredVec::new(meter);
        let mut offset: u64 = 0;
        for s in strings {
            let Ok(at) = u32::try_from(offset) else {
                break;
            };
            if at > 0x7FFF_FFFF {
                break;
            }
            let b = s.as_bytes();
            let len = std::str::from_utf8(b).map_or(b.len(), |t| t.chars().count());
            offset = offset.saturating_add(u64::try_from(len).unwrap_or(u64::MAX)) + 1;
            // A buffer made from a `Vec` allocates its shared header on its
            // first clone: make that clone here, not in a parse.
            drop(s.clone());
            entries.push((at, s))?;
        }
        let (entries, charge) = entries.into_boxed_slice()?;
        Ok(Self {
            entries,
            _charge: Some(charge),
        })
    }

    /// The string at `offset` (the low 31 bits), if the table has one.
    #[must_use]
    pub fn get(&self, offset: u32) -> Option<&RawStr> {
        let i = self
            .entries
            .binary_search_by_key(&offset, |(o, _)| *o)
            .ok()?;
        self.entries.get(i).map(|(_, s)| s)
    }

    /// The number of strings.
    #[must_use]
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Whether the table is empty (a blob's every common offset then reads
    /// as its decimal text).
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// `(offset, string)`, offsets ascending.
    pub fn iter(&self) -> impl Iterator<Item = (u32, &RawStr)> {
        self.entries.iter().map(|(o, s)| (*o, s))
    }
}

const _: () = crate::send_sync::<CommonStrings>();

impl std::fmt::Debug for CommonStrings {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("CommonStrings")
            .field("len", &self.entries.len())
            .finish_non_exhaustive()
    }
}

#[cfg(test)]
mod tests {
    use std::sync::Arc;

    use super::{COMMON_STRINGS, CommonStrings, common_string};
    use crate::RawStr;
    use crate::budget::{Reservation, Unbounded};
    use crate::error::LimitKind;
    use crate::limits::{ChargeError, Limits, Meter, heap_cost};

    #[test]
    fn the_table_is_unitypys_108_mit_strings_at_their_running_offsets() {
        assert_eq!(COMMON_STRINGS.len(), 108);
        // UnityPy numbers each string by the bytes before it, NULs included
        // (`helpers/TypeTreeNode.py:322-326`).
        let mut offset = 0;
        for &(o, s) in COMMON_STRINGS {
            assert_eq!(o, offset, "{}", String::from_utf8_lossy(s));
            assert_eq!(common_string(o), Some(s));
            offset += u32::try_from(s.len()).unwrap() + 1;
        }
        assert_eq!(common_string(0), Some(&b"AABB"[..]));
        // The last of the 108; whatever a TPK has after it is the TPK's.
        assert_eq!(common_string(1152), Some(&b"FileSize"[..]));
        assert_eq!(common_string(1161), None);
        assert_eq!(common_string(1), None);
    }

    /// `get_common_strings()` counts code points, not bytes: after `"é"`
    /// (two bytes, one code point) the next string is at 2. A string listed
    /// twice is numbered twice.
    #[test]
    fn a_run_time_table_numbers_strings_by_code_points() {
        let t = CommonStrings::new(
            ["é", "ab", "", "ab", "日本"].map(RawStr::from),
            &Meter::unlimited(),
        )
        .unwrap();
        let got: Vec<(u32, &[u8])> = t.iter().map(|(o, s)| (o, s.as_bytes())).collect();
        let want: Vec<(u32, &[u8])> = vec![
            (0, "é".as_bytes()),
            (2, b"ab"),
            (5, b""),
            (6, b"ab"),
            (9, "日本".as_bytes()),
        ];
        assert_eq!(got, want);
        assert_eq!(t.get(9).map(RawStr::as_bytes), Some("日本".as_bytes()));
        assert_eq!(t.get(1), None);
        assert_eq!(t.len(), 5);
        assert!(CommonStrings::default().is_empty());
    }

    /// A string at an offset no blob can name is left out, with every one
    /// after it.
    #[test]
    fn strings_past_the_31_bit_offsets_are_left_out() {
        let long = RawStr::from(vec![b'a'; 1 << 20]);
        // 2048 strings of 2^20 bytes and a NUL: the 2048th starts past 2^31.
        let t = CommonStrings::new(std::iter::repeat_n(long, 2049), &Meter::unlimited()).unwrap();
        assert_eq!(t.len(), 2048);
        let last = t.iter().last().unwrap().0;
        assert_eq!(u64::from(last), 2047 * ((1 << 20) + 1));
        assert!(last <= 0x7FFF_FFFF);
    }

    /// The table is as long as the strings a TPK lists, so it is charged to
    /// the meter it is built on, exactly its allocation once built, and
    /// returned when it is dropped; a meter without room refuses it.
    #[test]
    fn a_run_time_table_is_charged_to_its_meter() {
        let strings = || (0..1000).map(|_| RawStr::from_static(b"s"));
        let meter = Meter::unlimited();
        let t = CommonStrings::new(strings(), &meter).unwrap();
        assert_eq!(t.len(), 1000);
        let table = 1000 * std::mem::size_of::<(u32, RawStr)>();
        assert_eq!(meter.used(), heap_cost(u64::try_from(table).unwrap()));
        drop(t);
        assert_eq!(meter.used(), 0);
        let limits = Limits {
            max_input_memory: 4096,
            ..Limits::default()
        };
        let small = Meter::for_input(&limits, Arc::new(Unbounded), Reservation::Input);
        let refused = CommonStrings::new(strings(), &small).err();
        assert!(
            matches!(&refused, Some(ChargeError::Limit(l)) if l.kind == LimitKind::InputMemory),
            "{refused:?}"
        );
        assert_eq!(small.used(), 0);
    }
}
