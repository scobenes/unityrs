//! Compiles the deflate side of the vendored zlib 1.2.13
//! (`vendor/zlib-1.2.13/`, pristine: `vendor/zlib-1.2.13.sha256`) into a
//! static library that only this crate links.
//!
//! - `Z_PREFIX`: zconf.h renames the symbols the library defines, internal
//!   ones included (`_tr_init`, `_dist_code`, `zcalloc`), to `z_*`, so none
//!   is a symbol an unprefixed zlib defines (a system `libz`, a C library
//!   bundling zlib, `libz-sys`'s static build), whose names it would
//!   otherwise take, interpose or clash with at a static link. All but
//!   one: zlib's own name for its error strings is already `z_errmsg`,
//!   which zconf.h leaves alone, so `z_errmsg` is defined to
//!   `unityrs_z_errmsg` as well. A second `Z_PREFIX` zlib in one static
//!   link would still clash on every `z_*` name. (`Z_SOLO` would also drop
//!   `zcalloc`, but makes zlib define its own `zmemcpy`, `zmemcmp` and
//!   `zmemzero`, names `Z_PREFIX` leaves alone; so it is not defined, and
//!   `zutil.c` includes `gzguts.h`, vendored for it. zlib's `zcalloc` is
//!   never called: the crate always passes `zalloc` and `zfree` of its
//!   own, `src/zlib.rs`.) `tests/zlib.rs` reads the archive's symbols.
//! - `-fvisibility=hidden`, where the compiler takes it: no symbol leaves a
//!   shared object this crate is linked into (a Python extension), so the
//!   library neither interposes on nor is interposed by a zlib loaded beside
//!   it.
//! - `-std=gnu99`: zlib 1.2.13 defines its functions in the K&R style,
//!   which C23 removed; Clang rejects them in C23 mode. CI's build of the
//!   release tarball, for Pillow's side, uses the same standard.
//! - Optimised whatever the profile: deflate's bytes do not depend on it,
//!   and the debug build's tests deflate megabytes.
//! - The compiled deflate.c is an altered source version, derived in
//!   `OUT_DIR`. Only non-FASTEST `longest_match` is replaced; its pristine
//!   span must match the pinned SHA-256 before substitution. No vendored
//!   file is written. `test-reference` also builds pristine deflate.c with
//!   `unityrs_zref_` entry points, sharing the other four translation units.
//!
//! Only these files are compiled: deflate (`deflate.c`, `trees.c`), the
//! checksums (`adler32.c` for the zlib stream, `crc32.c` for PNG chunks) and
//! `zutil.c`.

use std::env;
use std::fmt::Write;
use std::fs;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

const ZLIB: &str = "vendor/zlib-1.2.13";
const SOURCES: [&str; 5] = ["adler32.c", "crc32.c", "deflate.c", "trees.c", "zutil.c"];
const HEADERS: [&str; 7] = [
    "crc32.h",
    "deflate.h",
    "gzguts.h",
    "trees.h",
    "zconf.h",
    "zlib.h",
    "zutil.h",
];
const MATCH: &str = "zlib-match/longest_match.c";
const REFERENCE: &str = "zlib-match/reference.c";
// deflate.c:1278-1423, from the function signature up to (but excluding)
// the newline before #else /* FASTEST */. Includes the final blank line.
const MATCH_SHA256: &str = "4093fbc81ac398951e68cb21c7cc0ece1add2bccce4023e033e6ac097d523e5f";

fn derived_deflate(dir: &Path, out: &Path) -> PathBuf {
    let original = fs::read_to_string(dir.join("deflate.c")).expect("read vendored deflate.c");
    let start = original
        .find("local uInt longest_match(s, cur_match)\n")
        .expect("zlib 1.2.13 non-FASTEST longest_match signature missing");
    let end = start
        + original[start..]
            .find("\n#else /* FASTEST */")
            .expect("zlib 1.2.13 longest_match end missing");
    let hash = Sha256::digest(&original.as_bytes()[start..end]);
    let digest = hash.iter().fold(String::new(), |mut s, b| {
        write!(s, "{b:02x}").expect("format longest_match SHA-256");
        s
    });
    assert_eq!(
        digest, MATCH_SHA256,
        "zlib 1.2.13 longest_match changed; refusing to patch an unreviewed source span"
    );
    let replacement = fs::read_to_string(MATCH).expect("read replacement longest_match");
    let derived = format!(
        "/* Altered source version: unityrs replaces non-FASTEST longest_match.\n\
         \x20* Generated by build.rs from pristine zlib 1.2.13; see zlib-match/.\n\
         \x20* This is not the original zlib source. */\n{}{}{}",
        &original[..start],
        replacement,
        &original[end..]
    );
    let path = out.join("deflate.c");
    fs::write(&path, derived).expect("write derived deflate.c in OUT_DIR");
    path
}

fn main() {
    let dir = Path::new(ZLIB);
    let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR"));
    let deflate = derived_deflate(dir, &out);
    let mut build = cc::Build::new();
    build
        .include(dir)
        .define("Z_PREFIX", None)
        .define("z_errmsg", Some("unityrs_z_errmsg"))
        .warnings(false)
        .opt_level(3)
        .flag_if_supported("-std=gnu99")
        .flag_if_supported("-fvisibility=hidden");
    for file in SOURCES {
        build.file(if file == "deflate.c" {
            deflate.clone()
        } else {
            dir.join(file)
        });
    }
    if env::var_os("CARGO_FEATURE_TEST_REFERENCE").is_some() {
        build.file(REFERENCE);
    }
    build.compile("unityrs_zlib");

    for file in SOURCES.iter().chain(HEADERS.iter()) {
        println!("cargo:rerun-if-changed={}", dir.join(file).display());
    }
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={MATCH}");
    println!("cargo:rerun-if-changed={REFERENCE}");
    // The target triple, for tests/flate2_backends.rs's `cargo metadata
    // --filter-platform`.
    let target = env::var("TARGET").unwrap_or_default();
    println!("cargo:rustc-env=UNITYRS_IMAGEIO_TARGET={target}");
    // The archive `compile` wrote, for tests/zlib.rs's symbol check.
    let archive = out.join("libunityrs_zlib.a");
    println!(
        "cargo:rustc-env=UNITYRS_IMAGEIO_ZLIB_ARCHIVE={}",
        archive.display()
    );
}
