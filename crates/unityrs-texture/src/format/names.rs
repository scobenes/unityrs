/// UnityPy 1.25.2's name for a `TextureFormat` value, or `None` for a value
/// its enum lacks (where `TextureFormat(value)` raises `ValueError`).
#[must_use]
pub fn texture_format_name(value: i32) -> Option<&'static str> {
    TEXTURE_FORMATS
        .iter()
        .find(|(v, _)| *v == value)
        .map(|(_, name)| *name)
}
