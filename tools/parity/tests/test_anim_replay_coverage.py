"""Complete the optional coverage fixtures fail-closed, and accept a run that predates them."""

import json
import sys
import unittest
from pathlib import Path
from unittest import mock

from anim_coverage_support import BUNDLES, COVERAGE, INTEGER, SETTINGS, TWIST, coverage_archives, turn
from anim_fixture_support import (DEFERRED, REPLAYS, RUN, STATIC, VECTORS, fixture_archives, stamp,
                                  static_bundles, write)
from test_anim_replay import bits

HERE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HERE))

import anim_fixture_coverage  # noqa: E402
import anim_replay as replay  # noqa: E402
from anim_replay_complete import read_manifest, recorded_paths  # noqa: E402
import child  # noqa: E402
import scratch  # noqa: E402


class CoverageCompletionTests(unittest.TestCase):
    def setUp(self):
        self.folder = scratch.for_case(self)
        self.inspect = self.folder / "inspection"
        self.replays = self.folder / "replays"
        self.bundles = self.folder / "bundles"
        for folder in (self.inspect, self.replays, self.bundles, self.replays / "known-vectors"):
            folder.mkdir()
        self.statuses = dict.fromkeys(COVERAGE, "recorded")
        self.recordings = fixture_archives(self.bundles, self.inspect)
        static_bundles(self.bundles, self.inspect)
        (self.folder / "build.log").write_text(stamp(RUN) + "\n", encoding="utf-8")
        (self.folder / "unityrs-generated.txt").write_text(
            "Generated by the unityrs fixture builder.\n" + stamp(RUN) + "\n", encoding="utf-8")

    def build(self, **kwargs):
        self.coverage = coverage_archives(self.bundles, self.inspect, **kwargs)

    def complete(self, *, written=COVERAGE):
        cases = [dict(name=name, status="recorded", reason="") for name in (*STATIC, *REPLAYS, *VECTORS)]
        for name in DEFERRED:
            status = self.statuses.get(name, "not_covered")
            cases.append(dict(name=name, status=status, reason="" if status == "recorded" else "Unity refused it"))
        write(self.folder / "run.json", dict(format="unityrs.fixture_run", version=1, run=RUN, cases=cases))
        for name, doc in self.recordings.items():
            write((self.replays / "known-vectors" if name in VECTORS else self.replays) / f"{name}.pending.json", doc)
        for name in written:
            write(self.replays / f"{name}.pending.json", self.coverage[name])
        return child.run([sys.executable, "-I", str(HERE / "anim_replay.py"), "complete", str(self.folder),
                          "--inspect-dir", str(self.inspect)], capture_output=True, text=True)

    def assert_refused(self, message, **kwargs):
        result = self.complete(**kwargs)
        self.assertEqual(result.returncode, 1, result.stdout)
        self.assertIn(message, result.stderr)
        self.assertEqual(list(self.replays.glob("*-refusal.json")), [])

    def completed(self, name):
        return replay.read_json((self.replays / f"{name}.json").read_text(encoding="utf-8"))

    def test_completes_recorded_coverage_with_its_evidence(self):
        self.build()
        result = self.complete()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("Completed and validated 18 replay(s)", result.stdout)
        self.assertIn("Optional coverage not recorded: integer-discrete-binding: not_covered", result.stdout)
        self.assertFalse((self.replays / f"{INTEGER}.json").exists())
        self.assertEqual(self.completed(TWIST)["spec"]["evidence"]["expected_refusal"], "unsupported_humanoid_twist")
        settings = self.completed(SETTINGS)["spec"]["evidence"]
        self.assertEqual(settings["expected_refusal"], "unsupported_humanoid_clip_settings")
        level = next(row for row in settings["import_settings"] if row["property"] == "level")
        self.assertEqual((level["effective"], level["serialized"]), (.125, .125))
        for name in COVERAGE:
            replay.validate(self.completed(name), self.bundles)

    def test_a_2022_run_without_coverage_fixtures_is_refused(self):
        # As an older run: no coverage bundles or recordings, each reported not covered.
        self.statuses = {}
        result = self.complete(written=())
        self.assertEqual(result.returncode, 1, result.stdout)
        for name in COVERAGE:
            self.assertIn(f"{name}: required for Unity 2022.3.62f3 but not_covered", result.stderr)
            self.assertFalse((self.replays / f"{name}.json").exists())

    def required(self, table, *, written=()):
        self.complete(written=written)
        with mock.patch.dict(anim_fixture_coverage.REQUIRED_COVERAGE, table, clear=True):
            return recorded_paths(self.folder, replay, *read_manifest(self.folder, replay))

    def test_both_versions_require_the_humanoid_refusals(self):
        self.assertEqual(anim_fixture_coverage.REQUIRED_COVERAGE, dict.fromkeys(("2022.3", "6000"), COVERAGE))
        self.assertEqual(anim_fixture_coverage.required_coverage("6000.6.9f1"), set(COVERAGE))
        self.assertEqual(anim_fixture_coverage.required_coverage("2021.3.45f1"), set())

    def test_an_unlisted_version_completes_without_coverage_and_reports_it(self):
        self.statuses = {}
        paths, _, _, uncovered = self.required({})
        self.assertEqual(len(paths), len(REPLAYS) + len(VECTORS))
        for name in (INTEGER, *COVERAGE):
            self.assertIn(f"{name}: not_covered (Unity refused it)", uncovered)

    def test_a_required_case_fails_a_run_that_does_not_record_it(self):
        self.statuses = {}
        with self.assertRaisesRegex(ValueError, "humanoid-twist-refusal: required for Unity 2022.3.62f3 but not_covered"):
            self.required({"2022.3": (TWIST,)})
        # Another version's requirement does not apply.
        self.assertEqual(len(self.required({"6000": (TWIST,)})[0]), len(REPLAYS) + len(VECTORS))

    def test_refuses_a_recorded_integer_case(self):
        # Built-in components expose no discrete integer binding, so no recording of it is defined.
        self.build()
        self.statuses[INTEGER] = "recorded"
        write(self.replays / f"{INTEGER}.pending.json", self.coverage[TWIST])
        self.assert_refused("integer-discrete-binding: no recording defined for this optional case")

    def test_refuses_an_integer_bundle(self):
        self.build()
        (self.bundles / "anim-discrete").write_bytes((self.bundles / BUNDLES[TWIST]).read_bytes())
        self.assert_refused("unexpected fixture bundle inventory")

    def test_a_failed_coverage_case_fails_the_run(self):
        self.statuses = {TWIST: "failed"}
        self.assert_refused("humanoid-twist-refusal: failed (Unity refused it)", written=())

    def test_unrecorded_coverage_may_leave_its_bundle_but_not_a_recording(self):
        self.build()
        self.statuses = {TWIST: "recorded"}
        self.assert_refused("unexpected pending recording: replays/humanoid-non-neutral-setting-refusal.pending.json")
        (self.replays / f"{SETTINGS}.pending.json").unlink()
        # 2022.3 requires it; where no version requires it, its built bundle may stay.
        self.assert_refused("humanoid-non-neutral-setting-refusal: required for Unity 2022.3.62f3 but not_covered",
                            written=(TWIST,))
        paths, _, _, uncovered = self.required({}, written=(TWIST,))
        self.assertIn(self.replays / f"{TWIST}.pending.json", paths)
        self.assertIn("humanoid-non-neutral-setting-refusal: not_covered (Unity refused it)", uncovered)
        self.assertTrue((self.bundles / BUNDLES[SETTINGS]).exists())

    def test_recorded_coverage_needs_its_recording_and_bundle(self):
        self.build()
        self.assert_refused("humanoid-twist-refusal: missing replays/humanoid-twist-refusal.pending.json",
                            written=(SETTINGS,))
        (self.bundles / BUNDLES[TWIST]).unlink()
        self.assert_refused("unexpected fixture bundle inventory")

    def test_refuses_unknown_bundles(self):
        self.build()
        (self.bundles / "anim-extra").write_bytes(b"UnityFS\0")
        self.assert_refused("unexpected fixture bundle inventory")

    def test_refuses_a_refusal_label_on_an_ordinary_fixture(self):
        self.build()
        self.recordings["generic-quaternion"]["spec"]["evidence"]["editor"]["expected_refusal"] = "unsupported_humanoid_twist"
        self.assert_refused("fixture refusal label mismatch for generic-quaternion")

    def test_refuses_a_missing_or_wrong_refusal_label(self):
        self.build()
        self.coverage[TWIST]["spec"]["evidence"]["editor"]["expected_refusal"] = "unsupported_humanoid_clip_settings"
        self.assert_refused("fixture refusal label mismatch for humanoid-twist-refusal")

    def test_twist_refuses_a_neutral_capture(self):
        self.build()
        self.coverage[TWIST]["capture"]["humanoid"]["lower_leg_twist"] = "00000000"
        self.assert_refused("captured Avatar settings differ from the probe's one trigger")

    def test_twist_refuses_a_constant_muscle_track(self):
        self.build(ramp=False)
        self.assert_refused("built twist muscle does not ramp to its authored value")

    def test_twist_refuses_a_muscle_mapped_to_another_bone(self):
        self.build()
        muscles = self.coverage[TWIST]["capture"]["humanoid"]["muscles"]
        next(row for row in muscles if row["name"] == "Left Arm Twist In-Out")["bone"] = 15
        self.assert_refused("captured muscle mapping mismatch: Left Arm Twist In-Out")
    def test_twist_refuses_swapped_built_avatar_fields(self):
        def edit(case, value):
            if case == TWIST:
                human = value["m_Avatar"]["m_Human"]["data"]
                human["m_ArmTwist"], human["m_ForeArmTwist"] = human["m_ForeArmTwist"], human["m_ArmTwist"]
            return value
        self.build(avatar=edit)
        self.assert_refused("built Avatar settings differ from the probe's one trigger")
    def test_twist_refuses_a_missing_built_muscle_slot(self):
        def edit(clip):
            clip["m_ClipBindingConstant"]["genericBindings"][-1]["attribute"] = 99
            return clip
        self.build(clips={TWIST: edit})
        self.assert_refused("missing built twist muscle slot: Left Forearm Twist In-Out")

    def test_twist_refuses_evidence_without_redistribution(self):
        self.build()
        for row in self.coverage[TWIST]["spec"]["evidence"]["editor"]["twist_effects"][3:]:
            row["neutral_f32"] = row["authored_f32"]
        self.assert_refused("fixture twist evidence does not show redistribution in both limbs")

    def test_twist_refuses_a_built_pose_off_the_authored_twist(self):
        self.build()
        doc = self.coverage[TWIST]
        node = doc["spec"]["evidence"]["editor"]["twist_effects"][0]["node"]
        doc["capture"]["samples"][-1]["pose"]["transforms"][node]["rotation"] = turn(11)
        self.assert_refused("built twist pose differs from the authored Avatar at LeftUpperArm")

    def test_twist_refuses_a_missing_limb(self):
        self.build()
        self.coverage[TWIST]["spec"]["evidence"]["editor"]["twist_effects"].pop()
        self.assert_refused("fixture twist evidence must cover the left arm and leg")

    def test_twist_refuses_other_clip_offsets(self):
        self.build()
        self.coverage[TWIST]["capture"]["clip_settings"]["mirror"] = True
        self.assert_refused("fixture refusal probe has another clip setting trigger")
    def test_settings_refuse_a_neutral_built_offset(self):
        def edit(clip):
            clip["m_MuscleClip"]["m_Level"] = 0.
            return clip
        self.build(clips={SETTINGS: edit})
        self.assert_refused("fixture refusal probe has another serialized clip setting trigger")
    def test_settings_refuse_an_absent_serialized_offset(self):
        def edit(clip):
            del clip["m_MuscleClip"]["m_Level"]
            return clip
        self.build(clips={SETTINGS: edit})
        self.assert_refused("fixture refusal probe is missing the serialized height offset")
    def test_settings_refuse_a_neutral_capture(self):
        self.build()
        self.coverage[SETTINGS]["capture"]["clip_settings"]["level"] = "00000000"
        self.assert_refused("fixture refusal probe has another clip setting trigger")

    def test_settings_refuse_an_extra_clip_trigger(self):
        self.build()
        self.coverage[SETTINGS]["capture"]["clip_settings"]["keepOriginalPositionY"] = True
        self.assert_refused("fixture refusal probe has another clip setting trigger")

    def test_settings_refuse_an_extra_serialized_trigger(self):
        def edit(clip):
            clip["m_MuscleClip"]["m_Mirror"] = True
            return clip
        self.build(clips={SETTINGS: edit})
        self.assert_refused("fixture refusal probe has another serialized clip setting trigger")

    def test_settings_refuse_a_non_neutral_avatar(self):
        def edit(case, value):
            if case == SETTINGS:
                value["m_Avatar"]["m_Human"]["data"]["m_LegTwist"] = .5
            return value
        self.build(avatar=edit)
        self.assert_refused("built Avatar settings differ from the probe's one trigger")

    def test_settings_refuse_a_captured_twist(self):
        self.build()
        self.coverage[SETTINGS]["capture"]["humanoid"]["upper_arm_twist"] = bits(.5)
        self.assert_refused("captured Avatar settings differ from the probe's one trigger")
    def test_settings_refuse_twist_evidence(self):
        self.build()
        twist = self.coverage[TWIST]["spec"]["evidence"]["editor"]["twist_effects"]
        self.coverage[SETTINGS]["spec"]["evidence"]["editor"]["twist_effects"] = json.loads(json.dumps(twist))
        self.assert_refused("fixture coverage evidence mismatch for humanoid-non-neutral-setting-refusal")


if __name__ == "__main__":
    unittest.main()
