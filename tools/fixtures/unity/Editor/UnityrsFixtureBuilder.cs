static partial class UnityrsFixtureBuilder
{
    const string AssetFolder = "UnityrsFixtures";
    const string Assets = "Assets/" + AssetFolder;
    const string Output = "UnityrsFixturesOutput";
    const string Marker = "unityrs-generated.txt";
    const string MarkerText = "Generated by the unityrs fixture builder.";
    const string LogFile = "build.log";

    static readonly string[] LegacyCases = { "legacy-explicit" };
    static readonly string[] GenericCases = {
        "generic-quaternion", "generic-euler", "generic-constant", "generic-offset-stepped", "generic-weighted",
        "generic-morph", "generic-object-reference", "generic-override-morph", "generic-null-override", "generic-scale"
    };
    static readonly string[] StaticCases = { "static-batch-scene", "static-primitives", "static-materials", "static-lod", "static-skin" };

    static string[] HumanoidCases(string rig, bool tall)
    {
        var names = new[] { rig + "-muscles", rig + "-muscles-offset" };
        var cases = names.Concat(names.Select(name => name + "-known-vectors"));
        return tall ? cases.ToArray() : cases.Concat(new[] { rig + "-body-motion" }).ToArray();
    }

    internal sealed class ReplayCase
    {
        public string Bundle, Prefab, Clip, Avatar = "", BindingAddress = "";
        public string ProbePath, ProbeProperty = "translation";
        public string ReplayName, ExpectedDiscovery = "";
        public string OutputName => ReplayName ?? Path.GetFileNameWithoutExtension(Clip);
        public int ProbeChannel = -1;
        public float First, Last;
        public float? HeldTime, HeldLeft, HeldRight;
        public float? Start, Stop;
        public Func<float, float[]> KnownMuscles;
        public string[] ObjectReferenceAssets;
        public bool ProbeMixedStorage;
        public bool IsHumanoid => Avatar.Length != 0;
    }

    sealed class Build
    {
        public readonly List<AssetBundleBuild> Bundles = new List<AssetBundleBuild>();
        public readonly List<ReplayCase> Replays = new List<ReplayCase>();
        public readonly Dictionary<string, string> StaticBundles = new Dictionary<string, string>();

        public void AddBundle(string name, params string[] assets)
        {
            Bundles.Add(new AssetBundleBuild {
                assetBundleName = name, assetNames = assets.OrderBy(path => path, StringComparer.Ordinal).ToArray()
            });
        }
    }

    [Serializable] sealed class RunCase
    {
        public string name, status = "failed", reason = "Fixture was never produced.";
    }

    [Serializable] sealed class RunManifest
    {
        public string format = "unityrs.fixture_run";
        public int version = 1;
        public RunCase[] cases;
    }

    sealed class RunReport
    {
        readonly Dictionary<string, RunCase> cases;
        readonly Action<string> log;

        public RunReport(Action<string> log)
        {
            this.log = log;
            cases = StaticCases.Concat(LegacyCases).Concat(GenericCases)
                .Concat(HumanoidCases("humanoid-compact", false)).Concat(HumanoidCases("humanoid-tall", true))
                .ToDictionary(name => name, name => new RunCase { name = name }, StringComparer.Ordinal);
        }

        public void AddDeferred(string name, string reason) => cases.Add(name, new RunCase {
            name = name, status = "not_covered", reason = reason
        });

        public void Set(string name, string status, string reason = "")
        {
            cases[name].status = status;
            cases[name].reason = reason;
        }

        public bool Try(string step, IEnumerable<string> names, Action action)
        {
            try
            {
                action();
                return true;
            }
            catch (Exception error)
            {
                string reason = step + ": " + error.Message;
                foreach (var name in names) Set(name, "failed", reason);
                log("ERROR " + reason);
                Debug.LogException(error);
                return false;
            }
        }

        public void Prepare(Build build, string step, string[] names, Action action)
        {
            int bundles = build.Bundles.Count, replays = build.Replays.Count;
            if (Try(step, names, action)) return;
            build.Bundles.RemoveRange(bundles, build.Bundles.Count - bundles);
            build.Replays.RemoveRange(replays, build.Replays.Count - replays);
        }

        public string[] Write(string directory, Regex projectPath)
        {
            var rows = cases.Values.OrderBy(row => row.name, StringComparer.Ordinal).ToArray();
            foreach (var row in rows)
            {
                row.reason = projectPath.Replace(row.reason, "<project>");
                log(row.status + " " + row.name + (row.reason.Length > 0 ? ": " + row.reason : ""));
            }
            File.WriteAllText(Path.Combine(directory, "run.json"), JsonUtility.ToJson(new RunManifest { cases = rows }, true));
            return rows.Where(row => row.status == "failed").Select(row => row.name).ToArray();
        }
    }

    [MenuItem("Tools/unityrs/Build and record all fixtures")]
    static void BuildAndRecord() => Run(true);

    [MenuItem("Tools/unityrs/Build fixtures only")]
    static void BuildOnly() => Run(false);

    static void Run(bool record)
    {
        var target = EditorUserBuildSettings.activeBuildTarget;
        string version = Application.unityVersion;
        string relative = Path.Combine(Output, version, target.ToString());
        string assetDirectory = Path.GetFullPath(Application.dataPath);
        string project = Path.GetDirectoryName(assetDirectory);
        string generated = Path.Combine(assetDirectory, AssetFolder);
        string output = Path.Combine(project, relative);
        string staging = output + ".b-" + Guid.NewGuid().ToString("N").Substring(0, 8);
        string stagedLog = Path.Combine(staging, LogFile);
        string[] failures;
        try
        {
            CheckOwned(output);
            Directory.CreateDirectory(staging);
            WriteMarker(staging);
            using (var log = new StreamWriter(stagedLog) { AutoFlush = true })
            {
                // Unity uses forward slashes in asset messages. The OS may use
                // a different separator and spelling for the same project path.
                string projectPattern = string.Join(@"[/\\]", project.Split('/', '\\').Select(Regex.Escape));
                var projectPath = new Regex(projectPattern, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
                void Log(string message) => log.WriteLine(projectPath.Replace(message, "<project>"));
                void UnityLog(string message, string stack, LogType type)
                {
                    if (type != LogType.Log) Log(type + " " + message);
                }
                Application.logMessageReceived += UnityLog;
                try
                {
                    Log("Unity " + version + " / " + target);
                    Require(!EditorApplication.isPlayingOrWillChangePlaymode && !AnimationMode.InAnimationMode(),
                        "Exit Play Mode and animation preview, then try again.");
                    Require(GraphicsSettings.currentRenderPipeline == null,
                        "Open an empty 3D (Built-in) project to build these fixtures.");
                    CheckOwned(generated);
                    Folder(Assets);
                    WriteMarker(generated);

                    var report = new RunReport(Log);
                    AddDeferredCases(report);
                    InFixtureScene(scene => {
                        Progress("Preparing fixtures", .05f);
                        var build = PrepareFixtures(report, scene);
                        BuildAndCapture(build, report, staging, target, record, Log);
                    });
                    failures = report.Write(staging, projectPath);
                    Log(failures.Length == 0 ? "Finished." : "Finished with fixture errors: " + string.Join(", ", failures));
                }
                catch (Exception error)
                {
                    Log("ERROR " + error.Message);
                    throw;
                }
                finally { Application.logMessageReceived -= UnityLog; }
            }
            Progress("Publishing results", .98f);
            Publish(staging, output);
            EditorUtility.ClearProgressBar();
            string location = "Unity " + version + " / " + target + "\n\nOutput in your project folder:\n" + relative;
            if (failures.Length == 0)
                EditorUtility.DisplayDialog("unityrs fixtures ready", location, "OK");
            else
                EditorUtility.DisplayDialog("unityrs fixtures built with errors",
                    "Could not prepare or record " + string.Join(", ", failures) + ". See build.log.\n\n" + location, "OK");
        }
        catch (Exception error)
        {
            EditorUtility.ClearProgressBar();
            Debug.LogException(error);
            if (File.Exists(stagedLog))
            {
                try
                {
                    CheckOwned(output);
                    Directory.CreateDirectory(output);
                    File.Copy(stagedLog, Path.Combine(output, LogFile), true);
                    WriteMarker(output);
                }
                catch (IOException logError) { Debug.LogException(logError); }
                catch (UnauthorizedAccessException logError) { Debug.LogException(logError); }
                catch (InvalidOperationException logError) { Debug.LogException(logError); }
            }
            EditorUtility.DisplayDialog("unityrs fixture build failed",
                error.Message + "\n\nSee the Unity Console and " + Path.Combine(relative, LogFile) + " if present.", "OK");
        }
        finally
        {
            EditorUtility.ClearProgressBar();
            if (Directory.Exists(staging))
            {
                try { Directory.Delete(staging, true); }
                catch (IOException cleanupError) { Debug.LogException(cleanupError); }
                catch (UnauthorizedAccessException cleanupError) { Debug.LogException(cleanupError); }
            }
        }
    }

    static void Progress(string step, float fraction) =>
        EditorUtility.DisplayProgressBar("unityrs fixtures", step, fraction);

    static void AddDeferredCases(RunReport report)
    {
        report.AddDeferred("urp-materials", "Requires the URP package and a separate URP project.");
        report.AddDeferred("packed-rotation-slopes", "Requires an imported clip that retains packed rotation slopes.");
        report.AddDeferred("authored-runtime-precedence", "Requires independently conflicting authorship and runtime values in the built clip.");
        report.AddDeferred("mixed-transform-storage", "The scale fixture varies interpolation by axis. A scale binding spanning runtime storage ranges was not verified.");
        report.AddDeferred("humanoid-twist-refusal", "No rig with non-neutral Avatar twist settings is generated.");
        report.AddDeferred("humanoid-non-neutral-setting-refusal", "No clip with non-neutral import settings is generated.");
        report.AddDeferred("humanoid-slot-axis-inventory", "The serialized body and muscle slots and runtime axis fields need an inspected crosswalk.");
        report.AddDeferred("humanoid-root-hips-comparison", "Qualification needs a comparison against the completed known-vector baselines.");
        report.AddDeferred("integer-discrete-binding", "This run verifies a PPtr transition. An integer discrete flag needs its own fixture.");
    }

    static void InFixtureScene(Action<Scene> action)
    {
        // Unity cannot create an additive scene while an untitled scene is open.
        for (int i = 0; i < SceneManager.sceneCount; i++)
        {
            var open = SceneManager.GetSceneAt(i);
            if (string.IsNullOrEmpty(open.path))
                Require(EditorSceneManager.SaveScene(open), "Save the untitled scene before building fixtures.");
        }
        var previous = SceneManager.GetActiveScene();
        var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Additive);
        try
        {
            Require(SceneManager.SetActiveScene(scene), "Could not activate the fixture scene.");
            action(scene);
        }
        finally
        {
            if (previous.IsValid()) SceneManager.SetActiveScene(previous);
            EditorSceneManager.CloseScene(scene, true);
        }
    }

    static Build PrepareFixtures(RunReport report, Scene scene)
    {
        var build = new Build();
        BuildStatic(build, report, scene);
        Progress("Preparing legacy and generic animation", .2f);
        report.Prepare(build, "Prepare legacy animation", LegacyCases, () => BuildLegacy(build));
        report.Prepare(build, "Prepare generic animation", GenericCases, () => BuildGeneric(build));
        Progress("Preparing humanoid animation", .35f);
        foreach (bool tall in new[] { false, true })
        {
            string name = tall ? "humanoid-tall" : "humanoid-compact";
            report.Prepare(build, "Prepare " + name, HumanoidCases(name, tall), () => BuildHumanoid(build, name, tall));
        }
        return build;
    }

    static void BuildAndCapture(Build build, RunReport report, string staging, BuildTarget target,
        bool record, Action<string> log)
    {
        if (build.Bundles.Count == 0) return;
        string bundles = Path.Combine(staging, "bundles");
        string replays = Path.Combine(staging, "replays");
        AssetBundleManifest manifest = null;
        Progress("Building asset bundles", .5f);
        if (!report.Try("Build asset bundles", build.StaticBundles.Keys.Concat(build.Replays.Select(fixture => fixture.OutputName)), () => {
            AssetDatabase.SaveAssets();
            Directory.CreateDirectory(bundles);
            manifest = BuildPipeline.BuildAssetBundles(bundles, build.Bundles.ToArray(),
                BuildAssetBundleOptions.ChunkBasedCompression | BuildAssetBundleOptions.StrictMode, target);
            Require(manifest != null, "Unity could not build the fixture bundles. See the log and Console.");
        })) return;

        var built = new HashSet<string>(manifest.GetAllAssetBundles(), StringComparer.Ordinal);
        foreach (var entry in build.StaticBundles)
        {
            if (built.Contains(entry.Value) && File.Exists(Path.Combine(bundles, entry.Value))) report.Set(entry.Key, "recorded");
            else report.Set(entry.Key, "failed", "Unity did not emit " + entry.Value + ".");
        }
        for (int i = 0; i < build.Replays.Count; i++)
        {
            var fixture = build.Replays[i];
            string name = fixture.OutputName;
            if (!record)
            {
                report.Set(name, "skipped", "The Build fixtures only menu item was used.");
                continue;
            }
            Progress("Recording " + name, .6f + .36f * i / build.Replays.Count);
            log("Recording " + name);
            report.Try("Record " + name, new[] { name }, () => {
                Require(built.Contains(fixture.Bundle) && manifest.GetAllDependencies(fixture.Bundle).Length == 0,
                    "Expected a self-contained replay bundle for " + name);
                Directory.CreateDirectory(replays);
                bool mixed = AnimReplayRecorder.RecordFixture(fixture, bundles, replays);
                report.Set(name, "recorded");
                if (mixed) report.Set("mixed-transform-storage", "recorded", "Verified in the built generic-scale clip.");
            });
        }
    }

    static void CheckOwned(string folder)
    {
        if (Directory.Exists(folder))
        {
            string marker = Path.Combine(folder, Marker);
            Require(File.Exists(marker) && File.ReadAllText(marker).TrimEnd('\r', '\n') == MarkerText,
                "Move the existing " + Path.GetFileName(folder) + " folder aside before building unityrs fixtures.");
        }
    }

    static void WriteMarker(string folder) =>
        File.WriteAllText(Path.Combine(folder, Marker), MarkerText + Environment.NewLine);

    static void Publish(string staging, string output)
    {
        CheckOwned(output);
        string prior = staging + ".previous";
        if (Directory.Exists(output)) Directory.Move(output, prior);
        try { Directory.Move(staging, output); }
        catch
        {
            if (Directory.Exists(prior)) Directory.Move(prior, output);
            throw;
        }
        if (Directory.Exists(prior))
        {
            try { Directory.Delete(prior, true); }
            catch (IOException error) { Debug.LogException(error); }
            catch (UnauthorizedAccessException error) { Debug.LogException(error); }
        }
    }

    static string Folder(string path)
    {
        if (!AssetDatabase.IsValidFolder(path))
        {
            int slash = path.LastIndexOf('/');
            Require(AssetDatabase.CreateFolder(path.Substring(0, slash), path.Substring(slash + 1)).Length > 0,
                "Could not create " + path);
        }
        return path;
    }

    static T Save<T>(T asset, string path) where T : Object
    {
        var existing = AssetDatabase.LoadAssetAtPath<T>(path);
        if (existing == null)
        {
            AssetDatabase.CreateAsset(asset, path);
            Require(AssetDatabase.Contains(asset), "Could not save " + path);
            return asset;
        }
        EditorUtility.CopySerialized(asset, existing);
        EditorUtility.SetDirty(existing);
        Object.DestroyImmediate(asset);
        return existing;
    }

    static string SavePrefab(GameObject root, string path)
    {
        Require(PrefabUtility.SaveAsPrefabAsset(root, path) != null, "Could not save " + path);
        return path;
    }

    static Transform Child(Transform parent, string name, Vector3 position)
    {
        var child = new GameObject(name).transform;
        child.SetParent(parent, false);
        child.localPosition = position;
        return child;
    }

    static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }
}
