    static void AddDeferredCases(RunReport report)
    {
        report.AddDeferred(UrpCase, "Requires a separate Universal 3D project: run " + UrpMenu + " there.");
        report.AddDeferred("packed-rotation-slopes", PackedSlopesReason);
