"""Generate unityrs-core's four tables from the oracle (docs/plans/core.md section 2.6).

Runs in the oracle image (UnityPy 1.25.2 on Python 3.11, Unicode 14.0.0) beside the
pinned Rust toolchain, and rewrites only the generated regions of three files:

    crates/unityrs-core/src/typetree/commonstring.rs   COMMON_STRINGS
    crates/unityrs-core/src/classid.rs                 CLASS_NAMES
    crates/unityrs-core/src/tables.rs                  ND_ZEROS, LOWER_EXCEPTIONS

A region starts at the line `// @generated by tools/gen/gen_tables.py from ...` and ends
at `// @generated end`; everything outside it (module docs, the lookups, the tests) is
hand-written and kept. Each table is asserted here before it is written:

- COMMON_STRINGS: `UnityPy.helpers.TypeTreeNode.get_common_strings()`, exactly 112
  `(offset, bytes)` pairs, each marked with its source: `enums/CommonString.py` (MIT) or
  the TPK UnityPy 1.25.2 ships. 1161 Hash128, 1169 RenderingLayerMask, 1188 fixed_array
  and 1200 EntityId are present, 1209 (rabex's LoadableReference) is absent.
- CLASS_NAMES: `UnityPy.enums.ClassIDType`, 368 members, sorted by id.
- ND_ZEROS: the zero of every run of Unicode `Nd` digits under Python 3.11's
  `unicodedata`; every `Nd` character is `zero + d` for its digit `d` in 0-9.
- LOWER_EXCEPTIONS: every code point whose `str.lower()` differs from Rust's
  `char::to_lowercase` under the pinned toolchain, with Python's answer. Rust's side is
  read from a small program this script compiles with that toolchain's `rustc`.

    scripts/dev python tools/gen/gen_tables.py           # write the tables
    scripts/dev python tools/gen/gen_tables.py --check   # regenerate and compare
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
import tomllib
import unicodedata
from pathlib import Path

import UnityPy
from UnityPy.enums import ClassIDType
from UnityPy.enums.CommonString import CommonString
from UnityPy.helpers.TypeTreeNode import get_common_strings

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "crates/unityrs-core/src"
GENERATOR = "tools/gen/gen_tables.py"

UNITYPY = "1.25.2"
PYTHON = (3, 11)
UNICODE = "14.0.0"

# The 2.6 assertions.
COMMON_COUNT = 112
COMMON_PRESENT = {1161: "Hash128", 1169: "RenderingLayerMask", 1188: "fixed_array", 1200: "EntityId"}
COMMON_ABSENT = (1209,)
CLASS_COUNT = 368

RUST_LOWER = r"""
fn main() {
    let (a, b, c) = char::UNICODE_VERSION;
    println!("{a} {b} {c}");
    for cp in 0u32..=0x10_FFFF {
        let Some(ch) = char::from_u32(cp) else { continue };
        let low: Vec<u32> = ch.to_lowercase().map(u32::from).collect();
        if low != [cp] {
            let hex: Vec<String> = low.iter().map(|c| format!("{c:x}")).collect();
            println!("{cp:x} {}", hex.join(","));
        }
    }
}
"""


def fail(msg: str) -> None:
    raise SystemExit(f"gen_tables: {msg}")


def check(cond: bool, msg: str) -> None:
    if not cond:
        fail(msg)


# --- the tables ---------------------------------------------------------------------


def common_strings() -> list[tuple[int, bytes, str]]:
    """`(offset, bytes, source)` in offset order (`helpers/TypeTreeNode.py:308-328`)."""
    table = get_common_strings()
    check(len(table) == COMMON_COUNT, f"get_common_strings() has {len(table)} entries, not {COMMON_COUNT}")
    for offset, name in COMMON_PRESENT.items():
        check(table.get(offset) == name, f"offset {offset} is {table.get(offset)!r}, not {name!r}")
    for offset in COMMON_ABSENT:
        check(offset not in table, f"offset {offset} is present ({table.get(offset)!r})")
    for offset, s in CommonString.items():
        check(table.get(offset) == s, f"CommonString.py's {offset} {s!r} is not in the table")
    out = []
    expected = 0
    for offset in sorted(table):
        s = table[offset]
        # The parser's offsets accumulate: each string and its NUL.
        check(offset == expected, f"offset {offset} follows {expected}")
        expected = offset + len(s.encode()) + 1
        source = "CommonString.py" if CommonString.get(offset) == s else "the TPK UnityPy ships"
        out.append((offset, s.encode(), source))
    return out


def class_names() -> list[tuple[int, str]]:
    """`ClassIDType`'s members, sorted by id (`enums/ClassIDType.py`)."""
    members = list(ClassIDType)
    check(len(members) == CLASS_COUNT, f"ClassIDType has {len(members)} members, not {CLASS_COUNT}")
    ids = [m.value for m in members]
    check(len(set(ids)) == len(ids), "ClassIDType repeats an id")
    for m in members:
        check(-(2**31) <= m.value < 2**31, f"{m.name} = {m.value} is not an i32")
        check(m.name.isascii() and m.name.isidentifier(), f"{m.name!r} is not a plain name")
    return sorted((m.value, m.name) for m in members)


def nd_zeros() -> list[int]:
    """The zero of each `Nd` run; asserts every `Nd` character is `zero + d`."""
    nd = [cp for cp in range(0x110000) if unicodedata.category(chr(cp)) == "Nd"]
    zeros = [cp for cp in nd if unicodedata.decimal(chr(cp)) == 0]
    nd_set = set(nd)
    zero_set = set(zeros)
    for cp in nd:
        d = unicodedata.decimal(chr(cp))
        check(0 <= d <= 9 and cp - d in zero_set, f"U+{cp:04X} is not a run's zero plus its digit")
    for z in zeros:
        for d in range(10):
            check(z + d in nd_set and unicodedata.decimal(chr(z + d)) == d, f"run at U+{z:04X} is short")
    check(len(nd) == 10 * len(zeros), "an Nd character outside the runs")
    check(zeros[0] == 0x30, "the first run is not ASCII")
    return zeros


def rust_lowercase(rustc_version: str) -> tuple[tuple[int, int, int], dict[int, str]]:
    """Rust's `char::to_lowercase` for every code point it changes, from the pinned rustc."""
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "lower.rs"
        exe = Path(tmp) / "lower"
        src.write_text(RUST_LOWER)
        subprocess.run(["rustc", "-O", "-o", str(exe), str(src)], cwd=ROOT, check=True)
        out = subprocess.run([str(exe)], check=True, capture_output=True, text=True).stdout
    lines = out.splitlines()
    major, minor, update = (int(x) for x in lines[0].split())
    mapping = {}
    for line in lines[1:]:
        cp, hexes = line.split()
        mapping[int(cp, 16)] = "".join(chr(int(h, 16)) for h in hexes.split(","))
    return (major, minor, update), mapping


def lower_exceptions(rust: dict[int, str]) -> list[tuple[int, str]]:
    """Code points whose Python 3.11 `str.lower()` differs from Rust's, with Python's."""
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue  # not a `char`; `py_lower` passes surrogate escapes through as bytes
        ch = chr(cp)
        py = ch.lower()
        if py != rust.get(cp, ch):
            out.append((cp, py))
    return out


def pinned_rustc() -> str:
    channel = tomllib.loads((ROOT / "rust-toolchain.toml").read_text())["toolchain"]["channel"]
    version = subprocess.run(["rustc", "-V"], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    check(version.split()[1] == channel, f"rustc is {version.strip()}, the toolchain pins {channel}")
    return channel


# --- rendering ----------------------------------------------------------------------


def rust_str(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append(f"\\u{{{ord(ch):x}}}")
    return '"' + "".join(out) + '"'


def rust_bytes(b: bytes) -> str:
    out = []
    for byte in b:
        ch = chr(byte)
        if ch in '"\\':
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append(f"\\x{byte:02x}")
    return 'b"' + "".join(out) + '"'


def region(source: str, decl: str, rows: list[str], extra: str = "") -> str:
    body = "".join(f"    {r}\n" for r in rows)
    return (
        f"// @generated by {GENERATOR} from {source}; do not edit.\n"
        "#[rustfmt::skip]\n"
        "#[allow(clippy::unreadable_literal)]\n"
        f"{decl} = &[\n{body}];\n{extra}// @generated end\n"
    )


def render_common(rows: list[tuple[int, bytes, str]]) -> str:
    lines = [f"({o}, {rust_bytes(b)}), // {src}" for o, b, src in rows]
    return region(
        f"UnityPy {UNITYPY} (UnityPy.helpers.TypeTreeNode.get_common_strings())",
        "pub static COMMON_STRINGS: &[(u32, &[u8])]",
        lines,
    )


def render_classes(rows: list[tuple[int, str]]) -> str:
    return region(
        f"UnityPy {UNITYPY} (UnityPy.enums.ClassIDType)",
        "pub static CLASS_NAMES: &[(i32, &str)]",
        [f"({i}, {rust_str(n)})," for i, n in rows],
    )


def render_nd(zeros: list[int]) -> str:
    rows = [", ".join(f"0x{z:04X}" for z in zeros[i : i + 8]) + "," for i in range(0, len(zeros), 8)]
    py = ".".join(str(x) for x in sys.version_info[:2])
    return region(
        f"Python {py} unicodedata (Unicode {unicodedata.unidata_version})",
        "pub static ND_ZEROS: &[u32]",
        rows,
    )


def render_lower(rows: list[tuple[int, str]], rust_unicode: tuple[int, int, int], rustc: str) -> str:
    py = ".".join(str(x) for x in sys.version_info[:2])
    extra = (
        f"/// Rust's Unicode version when the table was generated (rustc {rustc}).\n"
        "#[cfg(test)]\n"
        f"const RUST_UNICODE_VERSION: (u8, u8, u8) = {rust_unicode};\n"
    )
    return region(
        f"Python {py} str.lower() (Unicode {unicodedata.unidata_version}) against rustc {rustc}'s "
        "char::to_lowercase",
        "pub static LOWER_EXCEPTIONS: &[(u32, &str)]",
        [f"(0x{cp:04X}, {rust_str(py_s)})," for cp, py_s in rows],
        extra,
    )


def replace_region(text: str, name: str, new: str, path: Path) -> str:
    """Swaps the table `name`'s region (or the scaffold's `STUB(A)` seed) for `new`."""
    generated = re.compile(
        r"// @generated by tools/gen/gen_tables\.py [^\n]*\n"
        r"(?:(?!// @generated)[^\n]*\n)*?"  # the attributes
        rf"pub static {name}: [^\n]*\n"
        r"(?:(?!// @generated end\n)[^\n]*\n)*"  # the rows and anything after them
        r"// @generated end\n"
    )
    seed = re.compile(rf"// STUB\(A\)[^\n]*\npub static {name}: [^\n]*?= &\[[^\n]*\];\n")
    for pattern in (generated, seed):
        found = pattern.findall(text)
        if len(found) == 1:
            return pattern.sub(lambda _: new, text)
        check(not found, f"{path}: {len(found)} regions for {name}")
    fail(f"{path}: no region for {name}")
    return text


def generate() -> dict[Path, str]:
    check(UnityPy.__version__ == UNITYPY, f"needs UnityPy {UNITYPY}, found {UnityPy.__version__}")
    check(sys.version_info[:2] == PYTHON, f"needs Python {PYTHON}, found {sys.version_info[:2]}")
    check(unicodedata.unidata_version == UNICODE, f"needs Unicode {UNICODE}, found {unicodedata.unidata_version}")
    rustc = pinned_rustc()
    rust_unicode, rust_lower = rust_lowercase(rustc)

    regions = {
        CORE / "typetree/commonstring.rs": [("COMMON_STRINGS", render_common(common_strings()))],
        CORE / "classid.rs": [("CLASS_NAMES", render_classes(class_names()))],
        CORE / "tables.rs": [
            ("ND_ZEROS", render_nd(nd_zeros())),
            ("LOWER_EXCEPTIONS", render_lower(lower_exceptions(rust_lower), rust_unicode, rustc)),
        ],
    }
    out = {}
    for path, tables in regions.items():
        text = path.read_text()
        for name, new in tables:
            text = replace_region(text, name, new, path)
        out[path] = text
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="regenerate and compare, write nothing")
    args = ap.parse_args()
    stale = []
    for path, text in generate().items():
        if args.check:
            if path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        print("stale tables (run tools/gen/gen_tables.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
