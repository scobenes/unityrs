def source(name):
    data = (pathlib.Path(sys.argv[1]) / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != HASHES[name]:
        raise ValueError(f"unexpected source digest: {name}")
    return data.decode()


def array(text, name):
    match = re.search(r"\b" + name + r"(?:\[\d+\])+\s*\{(.*?)\n\};", text, re.S)
    if not match:
        raise ValueError(name)
    return match.group(1), text[:match.start()].count("\n") + 1


def numbers(text):
    return [int(n) for n in re.findall(r"\b\d+\b", text)]


