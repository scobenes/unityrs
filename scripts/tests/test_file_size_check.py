"""scripts/file-size-check.sh on scratch repositories: no tracked .rs or .py file
over 800 lines outside the allowlist.

Standard library only; needs git and sh.
"""

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parents[1] / "file-size-check.sh"

# Inherited, these would point the scratch repository's git at the
# checkout's (CLAUDE.md: they make `git init` write into the main config).
GIT_VARS = ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR")


def lines(n):
    return "".join(f"line {i}\n" for i in range(n))


class FileSizeCheckTests(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp(prefix="unityrs-file-size-"))
        self.addCleanup(shutil.rmtree, self.root)
        self.env = {k: v for k, v in os.environ.items() if k not in GIT_VARS}
        self.git("init", "-q")

    def git(self, *args):
        subprocess.run(["git", "-C", str(self.root), *args], env=self.env, check=True)

    def write(self, files, track=True):
        for path, text in files.items():
            p = self.root / path
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
            if track:
                self.git("add", "--", path)

    def check(self):
        run = subprocess.run(
            ["sh", str(SCRIPT), str(self.root)],
            env=self.env,
            capture_output=True,
            text=True,
            check=False,
        )
        return run.returncode, run.stdout, run.stderr

    def test_files_at_the_limit_pass(self):
        self.write({"crates/a/src/lib.rs": lines(800), "tools/b.py": lines(800)})
        code, out, err = self.check()
        self.assertEqual(code, 0, out + err)

    def test_each_file_over_the_limit_is_listed_longest_first(self):
        self.write(
            {
                "crates/a/src/lib.rs": lines(801),
                "crates/a/tests/big.rs": lines(900),
                "tools/b.py": lines(1200),
                "crates/a/src/small.rs": lines(10),
            }
        )
        code, out, err = self.check()
        self.assertEqual(code, 1)
        self.assertEqual(out.splitlines(), ["1200 tools/b.py", "900 crates/a/tests/big.rs", "801 crates/a/src/lib.rs"])
        self.assertIn("3 files over 800 lines", err)

    def test_the_allowlist_exempts_the_paths_it_names(self):
        allowlist = "# generated\ncrates/a/src/table.rs  # generated by gen.py\n\n  tools/gen.py # a fixture generator\n"
        self.write(
            {
                "scripts/file-size-allowlist.txt": allowlist,
                "crates/a/src/table.rs": lines(5000),
                "tools/gen.py": lines(900),
                "crates/a/src/lib.rs": lines(801),
            }
        )
        code, out, _ = self.check()
        self.assertEqual(code, 1)
        self.assertEqual(out.splitlines(), ["801 crates/a/src/lib.rs"])

    def test_an_allowlisted_path_must_match_whole(self):
        allowlist = "crates/a/src/table.rs  # generated\n"
        self.write(
            {
                "scripts/file-size-allowlist.txt": allowlist,
                "crates/b/crates/a/src/table.rs": lines(900),
                "crates/a/src/table.rs.rs": lines(900),
            }
        )
        code, out, _ = self.check()
        self.assertEqual(code, 1)
        self.assertEqual(len(out.splitlines()), 2, out)

    def test_only_tracked_rust_and_python_files_count(self):
        self.write({"notes.md": lines(2000), "data.json": lines(2000), "crates/a/src/lib.rs": lines(3)})
        self.write({"crates/a/src/untracked.rs": lines(2000)}, track=False)
        code, out, err = self.check()
        self.assertEqual(code, 0, out + err)

    def test_a_tracked_file_deleted_from_the_tree_is_skipped(self):
        self.write({"crates/a/src/lib.rs": lines(900)})
        (self.root / "crates/a/src/lib.rs").unlink()
        code, out, err = self.check()
        self.assertEqual(code, 0, out + err)

    def test_a_path_with_spaces_is_counted(self):
        self.write({"tools/a b.py": lines(801)})
        code, out, _ = self.check()
        self.assertEqual(code, 1)
        self.assertEqual(out.splitlines(), ["801 tools/a b.py"])


if __name__ == "__main__":
    unittest.main()
