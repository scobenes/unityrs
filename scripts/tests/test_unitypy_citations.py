def package(files: dict[str, str], head: dict[str, str]) -> C.Package:
    def shaped(texts):
        lines = {k: len(v.splitlines()) for k, v in texts.items()}
        shapes = {k: C.shape(v) if k.endswith(".py") else C.cpp_shape(v) for k, v in texts.items()}
        return lines, shapes

    return C.Package(*shaped(files), *shaped(head))


PACKAGE = package(UNITYPY, HEAD_FILES)


def write(root: Path, files: dict[str, str]):
    for rel, text in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(text)


class Checked(unittest.TestCase):
    def report(self, files: dict[str, str]):
        with scratch.folder("unityrs-citations-") as tmp:
            write(Path(tmp), files)
            return C.check(Path(tmp), PACKAGE)

    def assert_problem(self, report, text):
        self.assertTrue(any(text in p for p in report.problems), report.problems)

    def assert_passes(self, files, checked=None):
        report = self.report(files)
        self.assertEqual(report.problems, [])
        if checked is not None:
            self.assertEqual(report.checked, checked)
        return report


