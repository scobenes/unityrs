def unitypy_folder(root: Path, files: dict[str, str]) -> Path:
    write(root / "UnityPy", files)
    return root / "UnityPy"


def repository(root: Path, files: dict[str, str]) -> Path:
    """A repository holding `files` and the HEAD copies the script checks."""
    shutil.copytree(ROOT / C.HEAD_DIR, root / "repo" / C.HEAD_DIR, ignore=shutil.ignore_patterns("__pycache__"))
    write(root / "repo", files)
    return root / "repo"


class PackageTests(unittest.TestCase):
    def test_the_digest_of_a_package(self):
        files = {"environment.py": "a\n", "files/File.py": "x\n", "py.typed": "", "files/__pycache__/x.py": "y\n"}
        want = hashlib.sha256(
            "".join(
                f"{rel} {hashlib.sha256(text.encode()).hexdigest()}\n"
                for rel, text in sorted(files.items())
                if rel.endswith(".py") and "__pycache__" not in rel
            ).encode()
        ).hexdigest()
        with scratch.folder("unityrs-citations-") as tmp:
            folder = unitypy_folder(Path(tmp), files)
            self.assertEqual(C.package_digest(folder), want)
            (folder / "enums").mkdir()
            (folder / "enums" / "X.pyi").write_text("")
            self.assertNotEqual(C.package_digest(folder), want)

    def test_a_folder_that_is_not_the_pinned_package_is_refused(self):
        # Review round 12: a folder with no UnityPy in it passed, citing nothing it could check.
        with scratch.folder("unityrs-citations-") as tmp:
            repo = repository(Path(tmp), {})
            folder = unitypy_folder(Path(tmp), {"environment.py": "a\n"})
            (Path(tmp) / "empty").mkdir()
            for where in (folder, Path(tmp) / "empty", Path(tmp) / "missing"):
                with self.subTest(where.name), self.assertRaisesRegex(ValueError, "is not UnityPy 1.25.2's package"):
                    C.load_package(where, None, repo)
            digest = C.package_digest(folder)
            self.assertEqual(C.load_package(folder, None, repo, digest).lines["environment.py"], 1)
            (folder / "environment.py").write_text("b\n")
            with self.assertRaisesRegex(ValueError, "is not UnityPy 1.25.2's package"):
                C.load_package(folder, None, repo, digest)

    def test_the_head_copies_must_be_417d595s(self):
        with scratch.folder("unityrs-citations-") as tmp:
            repo = repository(Path(tmp), {})
            folder = unitypy_folder(Path(tmp), {"environment.py": "a\n"})
            got = C.load_package(folder, None, repo, C.package_digest(folder))
            self.assertEqual(set(got.head_lines), set(C.HEAD_FILES))
            with (repo / C.HEAD_DIR / "BundleFile.py").open("a") as fh:
                fh.write("\n")
            with self.assertRaisesRegex(ValueError, "is not files/BundleFile.py of UnityPy git 417d595"):
                C.load_package(folder, None, repo, C.package_digest(folder))


class CommandLineTests(unittest.TestCase):
    def main(self, args):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = C.main([str(a) for a in args])
        return code, out.getvalue(), err.getvalue()

    def test_a_run_on_a_package_and_a_repository(self):
        with scratch.folder("unityrs-citations-") as tmp:
            folder = unitypy_folder(Path(tmp), {"environment.py": "a\nb\n"})
            repo = repository(Path(tmp), {"a.md": f"`environment.py:{2}`, `:{1}`\n"})
            with mock.patch.object(C, "PACKAGE", C.package_digest(folder)):
                code, out, err = self.main([repo, "--unitypy", folder])
                self.assertEqual((code, err), (0, ""))
                self.assertIn(
                    "2 citations of UnityPy 1.25.2 in 1 files (1 of them bare lines, 0 UnityPyBoost's) name lines "
                    "that exist and whole spans (no blank first or last line; in UnityPy's Python no statement or "
                    "function cut, in UnityPyBoost's C++ no top-level definition cut); ",
                    out,
                )
                write(repo, {"a.md": f"`environment.py:{3}`\n"})
                code, out, err = self.main([repo, "--unitypy", folder])
                self.assertEqual((code, out), (1, ""))
                self.assertIn(f"a.md:1: environment.py:{3} is not a range of environment.py's 2 lines", err)
            # Unpatched, the stand-in is not UnityPy 1.25.2.
            code, _, err = self.main([repo, "--unitypy", folder])
            self.assertEqual(code, 2)
            self.assertIn("is not UnityPy 1.25.2's package", err)

    def test_a_folder_without_unitypy_is_a_usage_error(self):
        script = SCRIPTS / "unitypy_citations.py"
        with scratch.folder("unityrs-citations-") as tmp:
            repo = repository(Path(tmp), {"a.md": f"`environment.py:{2}`\n"})
            (Path(tmp) / "empty").mkdir()
            for folder in (Path(tmp) / "empty", Path(tmp) / "missing", repo):
                with self.subTest(folder.name):
                    args = [sys.executable, str(script), str(repo), "--unitypy", str(folder)]
                    run = child.run(args, capture_output=True, text=True)
                    self.assertEqual((run.returncode, run.stdout), (2, ""))
                    self.assertIn("is not UnityPy 1.25.2's package", run.stderr)


